#!/usr/bin/env python3
"""Generate docs/evidence/test_catalogue_generated.md from Maven Surefire XML reports.

Run after `mvn test` (or `mvn package`). Every row comes from an executed test case, so the
catalogue cannot list a test that did not run or a status that was not observed.
"""
import datetime
import glob
import os
import re
import xml.etree.ElementTree as ET

REPORTS = "target/surefire-reports/TEST-*.xml"
OUT = "docs/evidence/test_catalogue_generated.md"


def main():
    files = sorted(glob.glob(REPORTS))
    if not files:
        raise SystemExit("No Surefire reports found; run mvn test first.")
    rows, java = [], None
    for path in files:
        root = ET.parse(path).getroot()
        cls = root.get("name").split(".")[-1]
        props = {p.get("name"): p.get("value") for p in root.iter("property")}
        java = java or props.get("java.version")
        for tc in root.iter("testcase"):
            name = re.sub(r"^\w+\([^)]*\) ", "", tc.get("name"))
            if tc.find("failure") is not None or tc.find("error") is not None:
                status = "FAIL"
            elif tc.find("skipped") is not None:
                status = "NOT VERIFIED"
            else:
                status = "PASS"
            m = re.match(r"(TC-[A-Z]+-\d+)\s*(.*)", name)
            test_id, desc = (m.group(1), m.group(2)) if m else ("-", name)
            rows.append((test_id, desc, cls, tc.get("time"), status))
    rows.sort(key=lambda r: (r[0].split("-")[1], int(r[0].split("-")[2]), r[1]) if r[0] != "-" else ("~", 0, r[1]))
    run_time = datetime.datetime.fromtimestamp(os.path.getmtime(files[0])).strftime("%Y-%m-%d %H:%M")
    passed = sum(r[4] == "PASS" for r in rows)
    failed = sum(r[4] == "FAIL" for r in rows)
    skipped = sum(r[4] == "NOT VERIFIED" for r in rows)
    with open(OUT, "w") as out:
        out.write("# Generated test catalogue\n\n")
        out.write(f"Generated by `scripts/generate_test_catalogue.py` from the Maven Surefire XML reports of the run on "
                  f"{run_time} (local time).\n")
        out.write(f"Environment: Maven running on Java {java} (bytecode target: Java 17), MySQL 26.7.0 (Homebrew), "
                  f"Connector/J 8.4.0.\n\n")
        out.write(f"**Total: {len(rows)} tests | PASS {passed} | FAIL {failed} | NOT VERIFIED {skipped}**\n\n")
        out.write("| Test ID | Test case (input and expected result) | Class | Time (s) | Status |\n|---|---|---|---|---|\n")
        for r in rows:
            out.write(f"| {r[0]} | {r[1].replace('|', '/')} | {r[2]} | {r[3]} | {r[4]} |\n")
    print(f"{OUT}: {len(rows)} tests, {passed} pass, {failed} fail, {skipped} not verified")


if __name__ == "__main__":
    main()
